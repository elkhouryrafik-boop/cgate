"""
The blind test, as a test.

On 29 August 2026 a general-purpose agent with no knowledge of this tool wrote
`blind-rfp-schools.docx` and planted six defects in it. The list stayed sealed
until after the run. cgate 0.1.0 caught none of them, and the reason was
structural rather than a tuning failure: the extractor matched clauses against
fifteen integrity subjects, and not one of the six is an integrity subject.
Three of them are not properties of a single clause at all.

Each test below is one of those six. They are written against the document the
blind agent wrote, not against a fixture built to pass them, and they assert on
the quoted source text rather than on defect counts — so a check that fires for
the wrong reason, on the wrong clause, fails here.

The seventh test is the one that matters most in a year's time: it asserts the
run still reports what it did not read. A version of this tool that quietly
stops publishing its own coverage has given up the property that distinguishes
it from the lexicon it replaced.
"""

from __future__ import annotations

import os
import sys

import pytest

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from cgate.ingest import ingest
from cgate.lint import lint
from cgate.spec import compile_spec

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(HERE)
# Generated by `python examples/make_sample.py`. A missing file is a failure,
# never a skip: a silently skipped blind test proves nothing.
BLIND = os.path.join(REPO, "examples", "blind-rfp", "blind-rfp-schools.docx")


@pytest.fixture(scope="module")
def spec():
    doc = ingest(BLIND)
    return doc, lint(doc, compile_spec(doc))


def quotes(spec, check: str) -> str:
    _, s = spec
    return " ".join(q for d in s.defects if d.check == check for q in d.quotes)


def detail(spec, check: str) -> str:
    _, s = spec
    return " ".join(d.title + " " + d.detail for d in s.defects if d.check == check)


# ---------------------------------------------------------------------------
# The sealed list
# ---------------------------------------------------------------------------


def test_defect_1_bid_validity_90_on_the_cover_against_120_in_section_8(spec):
    q = quotes(spec, "value_conflict")
    assert "90 days" in q and "120 days" in q


def test_defect_1_the_bid_security_date_says_which_value_governs(spec):
    _, s = spec
    arith = [d for d in s.defects if d.check == "date_arithmetic"]
    assert len(arith) == 1
    assert arith[0].resolution == "120 days"
    assert "24 April 2027" in " ".join(arith[0].quotes)


def test_defect_2_turnover_750k_in_section_4_3_against_900k_in_section_5(spec):
    q = quotes(spec, "value_conflict")
    assert "USD 750,000" in q and "USD 900,000" in q


def test_defect_3a_the_payment_schedule_sums_to_95(spec):
    d = detail(spec, "table_sum")
    assert "95" in d
    assert "no total row" in d


def test_defect_3b_milestone_4_is_triggered_by_the_client_alone(spec):
    q = quotes(spec, "foreign_trigger")
    assert "Award of the works contract by the Foundation" in q


def test_defect_4_professional_indemnity_cover_is_stated_once_in_the_tor(spec):
    _, s = spec
    hit = [d for d in s.defects
           if d.check == "single_point_obligation"
           and "indemnity insurance" in " ".join(d.quotes)]
    assert len(hit) == 1
    assert "USD 1,500,000" in hit[0].quotes[0]
    assert "3.2" in hit[0].sections[0]


def test_defect_5_the_currency_and_tax_rule_voids_a_bid_from_the_evaluation_section(spec):
    _, s = spec
    hit = [d for d in s.defects if d.check == "disqualifying_rule_off_anchor"]
    assert hit
    q = " ".join(x for d in hit for x in d.quotes)
    assert "quoted in another currency" in q
    assert "non-responsive" in q
    assert any("6.4" in sec for d in hit for sec in d.sections)


def test_defect_6_the_team_leader_language_requirement_is_off_its_anchor(spec):
    _, s = spec
    hit = [d for d in s.defects if d.check == "personnel_requirement_off_anchor"]
    assert len(hit) == 1
    assert "Swahili" in " ".join(hit[0].quotes)
    assert "Team Leader" in hit[0].title


def test_all_six_planted_defects_are_covered_by_a_check(spec):
    _, s = spec
    raised = {d.check for d in s.defects}
    assert {
        "value_conflict",              # 1, 2
        "date_arithmetic",             # 1, resolved
        "table_sum",                   # 3a
        "foreign_trigger",             # 3b
        "single_point_obligation",     # 4
        "disqualifying_rule_off_anchor",  # 5
        "personnel_requirement_off_anchor",  # 6
    } <= raised


# ---------------------------------------------------------------------------
# The property that has to outlive the six
# ---------------------------------------------------------------------------


def test_the_run_still_reports_what_it_did_not_read(spec):
    _, s = spec
    assert s.blocks_total > 0
    assert s.blocks_compiled < s.blocks_total, "a run that claims total coverage is lying"
    assert len(s.uncompiled) == s.blocks_total - s.blocks_compiled
    for u in s.uncompiled:
        assert u["block_id"] and "text" in u


def test_every_defect_quotes_the_source_at_its_offsets(spec):
    doc, s = spec
    assert s.defects
    for d in s.defects:
        for sp in d.spans:
            assert doc.text_of(sp), f"{d.defect_id} cites an unresolvable span"


def test_no_check_reads_a_model_or_a_subject_lexicon(spec):
    # The blind document is about school rehabilitation. If a defect here
    # depended on the integrity lexicon, none of these would fire at all.
    _, s = spec
    assert len(s.defects) >= 9
