def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--out", default=HERE, help="examples directory (default: this one)")
    args = ap.parse_args(argv)

    out = os.path.abspath(args.out)
    repo = os.path.dirname(out)

    md = os.path.join(out, "blind-rfp", "blind-rfp-schools.md")
    if not os.path.exists(md):
        print(f"missing source {md}", file=sys.stderr)
        return 2
    rfp = os.path.join(out, "blind-rfp", "blind-rfp-schools.docx")
    md_to_docx(md, rfp, "Request for Proposals — invented, for testing")

    build_proposal(os.path.join(out, "proposal", "our-proposal.docx"))

    body = os.path.join(repo, "tests", "fixtures", "tender_body.txt")
    os.makedirs(os.path.dirname(body), exist_ok=True)
    with open(body, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(docx_text(rfp))

    write_fixtures(repo)
    print(f"wrote {rfp}")
    print(f"wrote {os.path.join(out, 'proposal', 'our-proposal.docx')}")
    print(f"wrote {body}")
    print(f"wrote {len(FIXTURE_TEXT)} bench fixtures under {os.path.join(repo, 'bench', 'fixtures')}")
    return 0


