def _scrub(path: str) -> None:
    """Replace docProps/app.xml (template path, company) with a neutral stub."""
    with open(path, "rb") as fh:
        src = zipfile.ZipFile(io.BytesIO(fh.read()))
    out = io.BytesIO()
    with zipfile.ZipFile(out, "w", zipfile.ZIP_DEFLATED) as dst:
        for item in sorted(src.infolist(), key=lambda i: i.filename):
            data = src.read(item.filename)
            if item.filename == "docProps/app.xml":
                data = _APP_XML.encode("utf-8")
            info = zipfile.ZipInfo(item.filename, date_time=(2026, 1, 1, 0, 0, 0))
            info.compress_type = zipfile.ZIP_DEFLATED
            dst.writestr(info, data)
    with open(path, "wb") as fh:
        fh.write(out.getvalue())


def _new_document(title: str) -> Document:
    d = Document()
    cp = d.core_properties
    cp.author = CREATOR
    cp.last_modified_by = CREATOR
    cp.title = title
    cp.subject = ""
    cp.keywords = ""
    cp.comments = "Synthetic document generated by examples/make_sample.py"
    cp.category = ""
    cp.created = STAMP
    cp.modified = STAMP
    cp.last_printed = STAMP
    cp.revision = 1
    return d


def _save(d: Document, path: str) -> None:
    os.makedirs(os.path.dirname(path), exist_ok=True)
    d.save(path)
    _scrub(path)


