_BOLD = re.compile(r"\*\*(.+?)\*\*")
_NUMBERED = re.compile(r"^\d+\.\s")


def _runs(par, text: str) -> None:
    pos = 0
    for m in _BOLD.finditer(text):
        if m.start() > pos:
            par.add_run(text[pos:m.start()])
        par.add_run(m.group(1)).bold = True
        pos = m.end()
    if pos < len(text):
        par.add_run(text[pos:])


def _split_row(line: str) -> list[str]:
    cells = line.strip().strip("|").split("|")
    return [c.strip() for c in cells]


def _table(d: Document, rows: list[list[str]]) -> None:
    ncols = max(len(r) for r in rows)
    t = d.add_table(rows=len(rows), cols=ncols)
    t.style = "Table Grid"
    for i, row in enumerate(rows):
        for j in range(ncols):
            cell = t.cell(i, j)
            text = row[j] if j < len(row) else ""
            _runs(cell.paragraphs[0], text)
            if i == 0:
                for r in cell.paragraphs[0].runs:
                    r.bold = True


def md_to_docx(md_path: str, out_path: str, title: str) -> None:
    """Headings keep the document's own numbering; tables become real tables;
    paragraphs are copied verbatim (inline ``**bold**`` becomes bold runs)."""
    with open(md_path, encoding="utf-8") as fh:
        lines = fh.read().splitlines()

    d = _new_document(title)
    i = 0
    while i < len(lines):
        line = lines[i]
        if not line.strip() or line.strip() == "---":
            i += 1
            continue
        if line.startswith("|"):
            block: list[list[str]] = []
            while i < len(lines) and lines[i].startswith("|"):
                if not re.fullmatch(r"\|[\s\-|:]+\|?", lines[i]):
                    block.append(_split_row(lines[i]))
                i += 1
            _table(d, block)
            continue
        m = re.match(r"^(#{1,3})\s+(.*)$", line)
        if m:
            d.add_heading(m.group(2).strip(), level=len(m.group(1)))
        elif line.startswith("- "):
            _runs(d.add_paragraph(style="List Bullet"), line[2:])
        else:
            # numbered items keep their literal "1." so the text matches the md
            _runs(d.add_paragraph(), line)
        i += 1
    _save(d, out_path)


def docx_text(path: str) -> str:
    """Plain text in reading order, tables as ' | '-joined rows, as `ingest` sees it."""
    from docx.table import Table
    from docx.text.paragraph import Paragraph

    src = Document(path)
    out: list[str] = []
    for child in src.element.body.iterchildren():
        tag = child.tag.split("}")[-1]
        if tag == "p":
            t = Paragraph(child, src).text.strip()
            if t:
                out.append(t)
        elif tag == "tbl":
            for row in Table(child, src).rows:
                cells = [c.text.strip() for c in row.cells]
                t = " | ".join(c for c in cells if c)
                if t:
                    out.append(t)
    return "\n\n".join(out) + "\n"


